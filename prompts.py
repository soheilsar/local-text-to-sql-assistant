"""Frozen prompts for the three-condition experiment.

Do NOT edit this file between model runs. If you change a word here, results
from before and after the change are no longer comparable and every model has
to be re-run.

Condition A  baseline      the database is described in words only (no schema, no rules)
Condition B  schema        A + exact view names, columns, types and allowed values
Condition C  schema_rules  B + the routing / aggregation / result-shape rules

None of the conditions contains few-shot examples. The production prompt in
sql_assistant.py does, so scores from this experiment are NOT comparable with
the 12/15 and 7/10 numbers in the README.
"""

CONDITIONS = {
    "A": "baseline",
    "B": "schema",
    "C": "schema_rules",
}

LABELS = {
    "A": "A: baseline (description only)",
    "B": "B: + schema",
    "C": "C: + schema + rules",
}

BASE = """You are a SQL assistant for a SQLite database.
The database belongs to a company. It stores the company's employees and the sales they made.
Convert the user's question into one SQLite query. Return only the SQL query, with no explanation."""

SCHEMA = """-- employee_sales: one row per sale (a view)
CREATE VIEW employee_sales (
  employee_id   INTEGER,  -- employee identifier
  employee_name TEXT,     -- first name only, for example 'Sara'
  department    TEXT,     -- one of: 'Retail', 'Online', 'Wholesale'
  product       TEXT,     -- one of: 'Laptop', 'Phone', 'Tablet', 'Monitor', 'Keyboard'
  amount        REAL,     -- value of the sale, between 50 and 2000
  sale_date     TEXT      -- format 'YYYY-MM-DD', all dates are in 2026 (January to October)
);

-- employees_list: one row per employee (a view). It has NO sales data.
CREATE VIEW employees_list (
  employee_id   INTEGER,
  employee_name TEXT,
  department    TEXT
);"""

# Copied from the rules block of SYSTEM_PROMPT in sql_assistant.py, minus the
# output-format rule (the BASE prompt already asks for SQL only).
RULES = """- Query ONLY the views employee_sales and employees_list. Never use any other table.
- To list employees when no sales figures are needed, use employees_list.
- For anything involving sales, amounts, products or dates, use employee_sales.
- When listing employees, always include both employee_id and employee_name.
- Questions that start with "How many" use COUNT(*), even if they also contain the word "total". Questions about money, revenue or amounts use SUM(amount).
- Use LIMIT when the user asks for a top N.
- If the question asks for the single highest, lowest or best item (for example "which department has the most sales"), return only that row using LIMIT 1. If the question gives a number N, use LIMIT N."""


def system_prompt(condition):
    parts = [BASE]
    if condition in ("B", "C"):
        parts.append("Database schema:\n" + SCHEMA)
    if condition == "C":
        parts.append("Rules:\n" + RULES)
    return "\n\n".join(parts)


def build_messages(condition, question):
    return [
        {"role": "system", "content": system_prompt(condition)},
        {"role": "user", "content": question},
    ]
